const savedCopyListeners=new Set();
async function invoke(action, ...args) {
  const response = await ipcRenderer.invoke(`pdfix:${action}`, ...args);
  if (!response.ok) { const error = new Error(response.error.message); error.code = response.error.code; throw error; }
  if(typeof response.value?.cleanupWarning==='string')setTimeout(()=>{for(const callback of outputWarnings)try{callback(response.value.cleanupWarning.slice(0,4096));}catch{}},0);
  if(typeof response.value?.continueToken==='string'&&typeof response.value?.name==='string'){const receipt={continueToken:response.value.continueToken,name:response.value.name};setTimeout(()=>{for(const callback of savedCopyListeners)try{callback(receipt);}catch{}},0);}
  return response.value;
}
