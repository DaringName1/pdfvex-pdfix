import {readFile,writeFile} from 'node:fs/promises';
// Generate packaged native validators from the same pure math used by the UI.
// This copies source; it never opens a document or launches a native worker.
const root=new URL('../',import.meta.url);
for(const [input,output]of [['drawing-measurement-math.js','pdf-takeoff-math.cjs'],['takeoff-ledger-model.js','pdf-takeoff-model.cjs'],['form-calculation-model.js','form-calculation-model.cjs'],['form-tab-order-model.js','form-tab-order-model.cjs']]){
 const source=await readFile(new URL('src/'+input,root),'utf8');
 const names=[...source.matchAll(/export (?:const|function) (\w+)/g)].map(match=>match[1]);
 const code=source.replace("import {MEASUREMENT_UNITS,pointDistance} from './drawing-measurement-math.js';","const {MEASUREMENT_UNITS,pointDistance}=require('./pdf-takeoff-math.cjs');").replace(/export (?=const |function )/g,'');
 await writeFile(new URL('desktop/'+output,root),'// Generated by scripts/sync-takeoff-model.mjs; edit the pure src model.\n'+code+'\nmodule.exports={'+names.join(',')+'};\n');
}
